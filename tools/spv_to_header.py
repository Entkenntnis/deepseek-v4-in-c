"""Turn a SPIR-V word stream into a C header.

Usage: spv_to_header.py INPUT.spv OUTPUT.h SYMBOL

The generated header defines a static uint32_t array and its byte length, so a
binary does not have to find a .spv file at runtime.
"""
import struct
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    src, dst, sym = sys.argv[1], sys.argv[2], sys.argv[3]
    data = open(src, "rb").read()
    if not data or len(data) % 4:
        print(f"{src}: not a SPIR-V word stream", file=sys.stderr)
        return 1
    words = struct.unpack("<%dI" % (len(data) // 4), data)

    with open(dst, "w", encoding="ascii") as f:
        f.write("/* Generated by tools/spv_to_header.py. Do not edit. */\n")
        f.write("#ifndef DSV4_GENERATED_SPV_H\n")
        f.write("#define DSV4_GENERATED_SPV_H\n\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        f.write(f"static const uint32_t {sym}[] = {{\n")
        for i in range(0, len(words), 8):
            row = ", ".join(f"0x{w:08x}u" for w in words[i:i + 8])
            f.write("    " + row + ",\n")
        f.write("};\n")
        f.write(f"static const size_t {sym}_len = sizeof {sym};\n\n")
        f.write("#endif\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
